"use client";

import type { V1RouterClient } from "@ecolens/api/routers/index";

import { useDataUser } from "@/components/shell/offline-data";
import { outbox, useOutbox } from "@/lib/offline/outbox";

export type ReportList = Awaited<ReturnType<V1RouterClient["reports"]["list"]>>;
export type ReportListItem = ReportList["items"][number];
export type Report = Awaited<ReturnType<V1RouterClient["reports"]["get"]>>;

export const REPORT_KIND: Record<ReportListItem["kind"], string> = {
  incident_assessment: "Incident assessment",
  alert_summary: "Alert summary",
  period_summary: "Period summary",
};

// Generating and approving reports go through the device outbox like every
// other workflow action. A report is generated by the server from the record
// as it stands when the request arrives.
export function useReportWrites() {
  const userId = useDataUser();
  const items = useOutbox(userId).filter((i) => i.path[0] === "reports");

  const generating = (target: { incidentId?: string; alertId?: string }) =>
    items.find(
      (i) =>
        i.path[1] === "generate" &&
        ((target.incidentId && i.input.incidentId === target.incidentId) ||
          (target.alertId && i.input.alertId === target.alertId)),
    ) ?? null;

  return {
    queued: items.filter((i) => i.path[1] === "generate"),
    generating,
    publishing: (id: string) =>
      items.find((i) => i.path[1] === "publish" && i.input.id === id) ?? null,
    async generate(target: { incidentId?: string; alertId?: string }, ref: string) {
      if (!userId) return null;
      return outbox.enqueue(userId, ["reports", "generate"], target, `Generate report on ${ref}`);
    },
    async publish(report: { id: string; ref: string }, note: string) {
      if (!userId) return;
      await outbox.enqueue(
        userId,
        ["reports", "publish"],
        { id: report.id, note },
        `Approve report ${report.ref}`,
      );
    },
  };
}
